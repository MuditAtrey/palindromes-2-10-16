"""C3: Coppersmith-style certificates for the inner test, degree 1 vs degree 2.

Inner test: is there x in {0,1}^n with f(x) = sum w_i x_i - t = 0 (mod N), N = 5^K?  (binary form: hex digit 6a + 9b.)
Lattice of polynomials h, multilinear in x (x_i^2 = x_i), with h(x) = 0 (mod N) at every root: generated by N * monomials, f, and for
degree 2 also x_k f. If sum |coefficients of h| < N then h(x) = 0 over the integers at every root. Enough independent such h with an
empty common solution set in {0,1}^n proves the target unreachable. Usable h are counted after LLL, then check the system by brute force
over the box (n small) to see whether it certifies. Reports, per K, the fraction of random targets certified dead by each degree.
"""
import sys, itertools, random, math
import numpy as np
from p_int import lll
def monos(n, deg):
    ms = [()] + [(i,) for i in range(n)]
    if deg >= 2: ms += [(i, j) for i in range(n) for j in range(i + 1, n)]
    return ms
def build(w, t, N, deg):
    n = len(w); ms = monos(n, deg); idx = {m: k for k, m in enumerate(ms)}
    gens = []
    f = [0] * len(ms); f[idx[()]] = -t
    for i in range(n): f[idx[(i,)]] = w[i]
    gens.append(f)
    if deg >= 2:
        for k in range(n):
            r = [0] * len(ms)
            r[idx[(k,)]] += -t + w[k]                   # x_k (w_k x_k) = w_k x_k ; x_k * (-t) = -t x_k
            for i in range(n):
                if i != k: r[idx[tuple(sorted((i, k)))]] += w[i]
            gens.append(r)
    # basis of {h : h = combination of gens (mod N)}: echelon form mod N with unit pivots, plus N e_c on the other columns
    G = [[c % N for c in g] for g in gens]; piv = []; rowsE = []
    for g in G:
        g = g[:]
        for (pc, pr) in zip(piv, rowsE):
            if g[pc]: c = g[pc]; g = [(a - c * b) % N for a, b in zip(g, pr)]
        pc = next((k for k in range(len(g)) if g[k] % 5), None)
        if pc is None: continue                      # no unit pivot: drop (sublattice, still sound)
        inv = pow(g[pc], -1, N); g = [a * inv % N for a in g]
        for k in range(len(rowsE)):
            c = rowsE[k][pc]
            if c: rowsE[k] = [(a - c * b) % N for a, b in zip(rowsE[k], g)]
        piv.append(pc); rowsE.append(g)
    rows = [r[:] for r in rowsE]
    for c in range(len(ms)):
        if c not in piv: r = [0] * len(ms); r[c] = N; rows.append(r)
    return ms, rows
def certify(w, t, N, deg, X):
    ms, rows = build(w, t, N, deg)
    red = [r for r in lll(rows) if any(r)]
    good = [r for r in red if sum(abs(c) for c in r) < N]
    if not good: return False, 0
    # evaluate all good h on the box: dead iff no x satisfies every h(x) = 0
    G = np.array(good, dtype=object)
    for x in X:
        vals = []
        mv = [1] + list(x) + ([x[i] * x[j] for i in range(len(x)) for j in range(i + 1, len(x))] if deg >= 2 else [])
        if all(sum(c * v for c, v in zip(h, mv)) == 0 for h in good): return False, len(good)
    return True, len(good)
if __name__ == "__main__":
    n = int(sys.argv[1]); trials = int(sys.argv[2]); Ks = [int(k) for k in sys.argv[3].split(',')]
    rnd = random.Random(7)
    X = list(itertools.product((0, 1), repeat=n))
    for K in Ks:
        N = 5 ** K
        inv = pow(16, -1, N)
        dig = [1] + [(pow(16, t, N) + pow(inv, t, N)) % N for t in range(1, n // 2)]
        w = []
        for v in dig: w += [6 * v % N, 9 * v % N]
        w = w[:n]
        reach = set()
        for x in X: reach.add(sum(a * b for a, b in zip(w, x)) % N)
        res = {1: 0, 2: 0}; ng = {1: 0, 2: 0}; tot = 0
        for _ in range(trials):
            t = rnd.randrange(N)
            if t in reach: continue
            tot += 1
            for deg in (1, 2):
                ok, g = certify(w, t, N, deg, X); res[deg] += ok; ng[deg] += g
        print(f"n={n} bits K={K} (density {n / (K * math.log2(5)):.2f}): unreachable targets {tot}; certified dead: degree 1 {res[1]}/{tot} "
              f"(usable h {ng[1]/max(tot,1):.1f}), degree 2 {res[2]}/{tot} (usable h {ng[2]/max(tot,1):.1f})", flush=True)
