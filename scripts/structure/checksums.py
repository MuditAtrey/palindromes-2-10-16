"""C4: which moduli m force a restricted residue on every decimal palindrome (or every hex palindrome) of a given length?
For a palindrome with D digits, N = sum_i d_i (b^i + b^(D-1-i)). The residues reachable mod m are the subgroup generated by the pair
weights (digits are free in 0..b-1, so multiples of every weight are reachable). Information = log2(m / |subgroup|)."""
import math
def info(b, D, m):
    g = m
    for i in range((D + 1) // 2):
        w = (pow(b, i, m) + pow(b, D - 1 - i, m)) % m if i != D - 1 - i else pow(b, i, m)
        g = math.gcd(g, w)
    return math.log2(g)            # residues lie in the subgroup g Z/m: m/g of them, so log2(g) bits of constraint
for b, name in ((10, "decimal"), (16, "hex")):
    best = {}
    for D in range(20, 40):
        for m in range(2, 20000):
            v = info(b, D, m)
            if v > 0.01:
                best.setdefault(m, []).append((D, round(v, 2)))
    # report moduli that constrain, with the lengths
    print(f"{name} palindromes: moduli (< 20000) that force a fixed subgroup, lengths 20-39:")
    for m in sorted(best)[:40]:
        Ds = sorted(set(D % 2 for D, _ in best[m])); print(f"   m={m:5d}: bits {max(v for _, v in best[m]):.2f}, lengths with parity {Ds}")
